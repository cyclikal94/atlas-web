// @vitest-environment node
import { describe, expect, test } from "vitest";
import { runOwnDetection, runStageTrigger } from "./matrix-activities";
import { runClosing } from "./matrix-closing";
import { runExposure } from "./matrix-exposure";
import type { Modules } from "./modules";
import { srcModules } from "./modules";
import witnesses from "./mutant-witnesses.json";
import { buildMutant, MUTANTS } from "./mutants";

/**
 * F-FID mutation detection (plan WP0 exit criteria). The matrix's eight send-model and eight exposure-model mutations
 * each remove ONE rule; each must be CAUGHT by the property checkers, and the same scenario must be CLEAN on the
 * unmutated source. `mutant-witnesses.json` holds, for each mutation, the scenarios the full-product search found
 * (regenerated by `pnpm test:session-matrix`, which searches the whole product and fails if a mutation is uncaught).
 * A fake that cannot fail a broken protocol is not evidence.
 */
type Witness = { family: string; params: never; violation: string };
const run = (
  family: string,
  params: never,
  modules: Modules,
): Promise<{ violations: string[] }> => {
  switch (family) {
    case "request":
    case "own":
    case "foreign":
      return runClosing(params, modules);
    case "detection":
      return runOwnDetection(params, modules);
    case "stage":
      return runStageTrigger(params, modules);
    case "exposure":
      return runExposure(params, modules);
    default:
      throw new Error(`unknown family ${family}`);
  }
};

describe("mutation detection", () => {
  test("there are eight send-model and eight exposure-model mutations", () => {
    expect(MUTANTS).toHaveLength(16);
    expect(new Set(MUTANTS.map((m) => m.name)).size).toBe(16);
    expect(Object.keys(witnesses).sort()).toEqual(
      MUTANTS.map((m) => m.name).sort(),
    );
  });

  for (const mutant of MUTANTS) {
    test(`${mutant.name}: "${mutant.rule}" is caught, and the witness is clean on the source`, async () => {
      const modules = await buildMutant(mutant);
      const list =
        (witnesses as unknown as Record<string, Witness[]>)[mutant.name] ?? [];
      expect(list.length).toBeGreaterThan(0);
      let caught = false;
      for (const witness of list) {
        const broken = await run(witness.family, witness.params, modules);
        const wanted = mutant.expect.split(" or ");
        if (
          broken.violations.some((v) =>
            wanted.some((w) => v.startsWith(w) || v.includes(w)),
          )
        )
          caught = true;
        const control = await run(witness.family, witness.params, srcModules);
        expect(control.violations).toEqual([]);
      }
      expect(caught).toBe(true);
    }, 60_000);
  }
});
